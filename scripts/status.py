#!/usr/bin/env python3
"""Deterministic B1 progress from the plan, optionally supplemented by open PRs."""

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATES = ("merged", "in review", "in progress", "not started")
GENERATED = "Generated by `make status`; do not edit by hand."


@dataclass
class Card:
    id: str
    title: str
    wave: int
    status: str
    tier2: bool


def parse_plan(path: Path) -> list[Card]:
    cards, wave, active = [], 0, False
    for block in re.split(
        r"(?=^#{1,6} )", path.read_text(encoding="utf-8"), flags=re.M
    ):
        heading = block.splitlines()[0] if block else ""
        if heading.startswith("## "):
            active = heading.startswith("## 4b.")
        if not active:
            continue
        if match := re.match(r"### Wave (\d+)\b", heading):
            wave = int(match[1])
        if match := re.match(r"### (T-B1-\d{3}b?): (.+)", heading):
            status = re.search(r"^Status:(.*)$", block, re.M)
            cards.append(
                Card(
                    match[1],
                    match[2],
                    wave,
                    status[1].strip() if status else "",
                    bool(re.search(r"Tier:\s*T2\b", block)),
                )
            )
    return cards


def classify(status: str) -> str:
    status = status.lower()
    # The leading bold phrase states the card's state; the rest may mention earlier steps
    # ("in progress: data part merged ..."), so it decides when present (lead review).
    lead = re.match(r"\s*(?:status:)?\s*\*\*(.+?)\*\*", status)
    if lead:
        status = lead.group(1)
    if re.search(r"\b(merged|delivered)\b", status):
        return "merged"
    if re.search(r"\bpr #\d+\b", status):
        return "in review"
    if re.search(r"\b(in progress|running)\b", status):
        return "in progress"
    return "not started"


def gh_json(*args: str) -> list[dict] | dict:
    result = subprocess.run(
        ["gh", "pr", *args], capture_output=True, text=True, check=True, timeout=15
    )
    return json.loads(result.stdout)


def open_prs() -> list[dict]:
    try:
        prs = gh_json(
            "list",
            "--state",
            "open",
            "--json",
            "number,title,headRefName,statusCheckRollup",
        )
        for pr in prs:
            pr.update(gh_json("view", str(pr["number"]), "--json", "body"))
        return prs
    except (OSError, subprocess.SubprocessError, ValueError) as error:
        print(f"Warning: gh failed; using plan only ({error}).", file=sys.stderr)
        return []


def render(cards: list[Card], prs: list[dict]) -> str:
    counts = {
        wave: dict.fromkeys(STATES, 0) for wave in sorted({c.wave for c in cards})
    }
    waiting, blocked = set(), []
    owner_rule = r"the owner merges|\btier\s*2\b|\btier:\s*t2\b"
    for card in cards:
        matches = [
            pr
            for pr in prs
            if re.search(rf"(?<![\w-]){re.escape(card.id)}(?![\w-])", pr["title"])
        ]
        state = "in review" if matches else classify(card.status)
        counts[card.wave][state] += 1
        if state == "in review" and (
            card.tier2 or re.search(owner_rule, card.status, re.I)
        ):
            numbers = [pr["number"] for pr in matches] or re.findall(
                r"PR #(\d+)", card.status
            )
            waiting.update(f"PR #{number} ({card.id})" for number in numbers)
        if re.search(r"\b(blocked|waits for)\b", card.status, re.I):
            blocked.append(f"{card.id}: {card.status}")
    for pr in prs:
        if re.search(owner_rule, pr["title"] + " " + pr.get("body", ""), re.I):
            if not any(item.startswith(f"PR #{pr['number']} (") for item in waiting):
                waiting.add(f"PR #{pr['number']}: {pr['title']}")
    lines = [
        GENERATED,
        "",
        "# B1 progress",
        "",
        "Counts: CALCULATED from plan statuses and optional open PRs.",
    ]
    totals = {state: sum(row[state] for row in counts.values()) for state in STATES}
    for label, row in [(f"Wave {wave}", row) for wave, row in counts.items()] + [
        ("Total", totals)
    ]:
        lines += [
            "",
            f"## {label}",
            "",
            "| " + " | ".join(STATES) + " |",
            "| --- | --- | --- | --- |",
            "| " + " | ".join(str(row[s]) for s in STATES) + " |",
        ]
    for label, items in [("Waiting for Ahmed", sorted(waiting)), ("Blocked", blocked)]:
        lines += ["", f"## {label}", ""] + (
            [f"- {item}" for item in items] or ["None."]
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, default=ROOT / "docs/COLLAB_PLAN.md")
    parser.add_argument(
        "--gh", action="store_true", help="Supplement the plan with open PRs"
    )
    parser.add_argument(
        "--write", type=Path, help="Write the same Markdown printed to stdout"
    )
    args = parser.parse_args(argv)
    output = render(parse_plan(args.plan), open_prs() if args.gh else [])
    if args.write:
        args.write.write_text(output, encoding="utf-8")
    print(output, end="")


if __name__ == "__main__":
    main()
